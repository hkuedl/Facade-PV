def read_hdf(path: Path) -> pd.DataFrame:
    try:
        return pd.read_hdf(path, key="df")
    except ImportError as exc:
        raise ImportError(
            "PyTables is required to read the Fig_input_data HDF files. "
            "Install it in the Python environment with `pip install tables`."
        ) from exc


def infer_column(df: pd.DataFrame, candidates: list[str], label: str) -> str:
    for candidate in candidates:
        if candidate in df.columns:
            return candidate
    raise KeyError(
        f"Cannot infer {label} from {candidates}; available columns={list(df.columns)}"
    )


def value_column(df: pd.DataFrame, preferred: str, source: str) -> str:
    if preferred in df.columns:
        return preferred
    if len(df.columns) == 1:
        return df.columns[0]
    raise KeyError(
        f"{source} must contain '{preferred}' or exactly one value column; "
        f"available columns={list(df.columns)}"
    )


def hdf_metric_with_grid_ids(
    path: Path, preferred_value: str, output_value: str
) -> pd.DataFrame:
    raw = read_hdf(path)
    value_col = value_column(raw, preferred_value, path.name)
    flat = raw.reset_index()
    city_col = infer_column(flat, ["city", "City", "level_0"], "city column")
    grid_col = infer_column(
        flat,
        [
            "grid_index",
            "grid_number",
            "grid_num",
            "Grid_number",
            "Grid_Number",
            "grid",
            "Grid",
            "level_1",
            "index",
        ],
        "grid column",
    )
    out = flat[[city_col, grid_col, value_col]].copy()
    out.columns = ["city", "grid_index", output_value]
    out["grid_index"] = out["grid_index"].astype(int)
    return out


def require_columns(df: pd.DataFrame, columns: list[str], label: str) -> None:
    missing = [column for column in columns if column not in df.columns]
    if missing:
        raise KeyError(f"{label} is missing required columns: {missing}")


def read_city_main_case(root: Path) -> pd.DataFrame:
    city_path = FIG_INPUT_DIR / "main_case_city_totals.csv"
    if not city_path.exists():
        raise FileNotFoundError(
            f"Missing {city_path}. Download or regenerate the public inputs."
        )

    city = pd.read_csv(city_path)
    require_columns(
        city,
        [
            "City",
            "case_id",
            "rpv_installability",
            "fpv_installability_of_filtered_AOI",
            "rpv_capacity_GW",
            "fpv_capacity_GW",
            "fpv_generation_TWh",
            "fpv_carbon_Mt",
        ],
        city_path.name,
    )
    case_ids = set(city["case_id"].dropna().astype(str))
    if case_ids != {MAIN_CASE_ID}:
        raise ValueError(
            f"The city-level file is not the unique main case {MAIN_CASE_ID}: "
            f"found {sorted(case_ids)}"
        )
    if not np.allclose(city["rpv_installability"].to_numpy(float), 0.35):
        raise ValueError("The saved main case is not uniformly RPV=0.35.")
    if not np.allclose(
        city["fpv_installability_of_filtered_AOI"].to_numpy(float),
        MAIN_FPV_INSTALLABILITY,
    ):
        raise ValueError("The saved main case is not uniformly FPV=0.70.")
    if city["City"].duplicated().any():
        duplicated = city.loc[city["City"].duplicated(), "City"].tolist()
        raise ValueError(f"Duplicated cities in the main-case CSV: {duplicated}")
    return city


