"""
Rebuild Fig. 4 with the FPV main case.

Scientific scope
----------------
Fig. 4a explains grid-level FPV generation potential. The original HDF inputs
were generated with an FPV effective-area coefficient of 0.90. The main
main case uses 0.70 within the facade AOI, so capacity and generation are
converted by 0.70 / 0.90 before model fitting and plotting.

Fig. 4b reads the FPV=0.70, RPV=0.35 optimization results generated by
`Optimization/Multi_period_planning.py` and re-aggregates four zone-share
pies:
    upper-left  : Facade Area
    upper-right : Roof Area
    lower-left  : FPV carbon mitigation
    lower-right : RPV carbon mitigation

Definition choices for Fig. 4b
-------------------------------
1. Area is defined consistently for facade and roof as *main-case installable
   PV surface equivalent area*. Practically, this is reconstructed from the
   city main-case installable capacities and converted with one common nominal
   PV power density, so the zone shares are comparable across facade and roof.
   Using installable area is more consistent with the deployment and carbon-
   mitigation pies than using total geometric area.
2. FPV carbon mitigation is defined as the incremental mitigation from adding
   FPV on top of the optimized RPV pathway, i.e. (roof pathway carbon) minus
   (roof+facade pathway carbon), accumulated over all five planning periods.
3. RPV carbon mitigation is defined consistently as the mitigation of the
   optimized roof pathway relative to a no-PV baseline, accumulated over the
   same five planning periods. The no-PV baseline carbon is reconstructed from
   the saved grid loads and implied city-year carbon factors in the MAT files.

Run order
---------
1. Download the prepared public inputs or regenerate the installability tables.
2. python #Codes/Optimization/Multi_period_planning.py
3. python #Codes/Figures/Fig_new_4.py

PDF and 600 dpi PNG figures are written to:
    <repository>/#Codes/Figures/Figs_new/
"""

