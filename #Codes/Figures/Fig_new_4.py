def validate_optimization_arrays(
    city: str,
    grid_type: np.ndarray,
    r_pow_f: np.ndarray,
    r_car: np.ndarray,
    r_pow: np.ndarray,
    r_pow_buy: np.ndarray,
    r_car_t: np.ndarray,
) -> None:
    if grid_type.ndim != 2 or grid_type.shape[1] < 5:
        raise ValueError(
            f"{city}: Grid_type must be a 2-D array with at least five columns; shape={grid_type.shape}"
        )
    if r_pow_f.ndim != 4:
        raise ValueError(f"{city}: R_Pow_f must be 4-D; shape={r_pow_f.shape}")
    if r_car.ndim != 3 or r_car.shape[1] < 2:
        raise ValueError(f"{city}: R_Car must have shape [grid, 2, year]; shape={r_car.shape}")
    if r_pow.ndim != 4:
        raise ValueError(f"{city}: R_Pow must be 4-D; shape={r_pow.shape}")
    if r_pow_buy.ndim != 5 or r_pow_buy.shape[1] < 2:
        raise ValueError(f"{city}: R_Pow_Buy must have shape [grid, 2, year, day, hour]; shape={r_pow_buy.shape}")
    if r_car_t.ndim != 5 or r_car_t.shape[1] < 2:
        raise ValueError(f"{city}: R_Car_t must have shape [grid, 2, year, day, hour]; shape={r_car_t.shape}")
    n_grid = grid_type.shape[0]
    if any(arr.shape[0] != n_grid for arr in [r_pow_f, r_car, r_pow, r_pow_buy, r_car_t]):
        raise ValueError(
            f"{city}: grid counts disagree among Grid_type ({n_grid}), R_Pow_f ({r_pow_f.shape[0]}), "
            f"R_Car ({r_car.shape[0]}), R_Pow ({r_pow.shape[0]}), R_Pow_Buy ({r_pow_buy.shape[0]}), and R_Car_t ({r_car_t.shape[0]})."
        )
    if not (r_pow_f.shape[1] == r_car.shape[2] == r_pow.shape[1] == r_pow_buy.shape[2] == r_car_t.shape[2]):
        raise ValueError(f"{city}: planning-year counts disagree among saved MAT arrays.")


def _scale_to_saved_total(target: float, raw_total: float, city: str, label: str) -> float:
    target = float(target)
    raw_total = float(raw_total)
    if not np.isfinite(target) or target < 0:
        raise ValueError(f"{city}: invalid saved {label} target: {target}")
    if not np.isfinite(raw_total) or raw_total <= 0:
        if target == 0:
            return 0.0
        raise ValueError(f"{city}: invalid raw {label} total: {raw_total}")
    return target / raw_total


def _indices_non_zero_from_features(city: str, city_feature_dir: Path) -> np.ndarray:
    feature_path = city_feature_dir / f"{city}_ALL_Featuers.npy"
    if not feature_path.exists():
        raise FileNotFoundError(f"Missing {feature_path}")
    feature = np.load(feature_path)
    if feature.ndim != 2 or feature.shape[1] <= 11:
        raise ValueError(f"{city}: unexpected feature shape {feature.shape} in {feature_path}")
    return np.where(feature[:, 11] != 0)[0]


def _align_grid_level_arrays(
    city: str,
    grid_type: np.ndarray,
    cap_roof_raw: np.ndarray,
    cap_facade_raw: np.ndarray,
    city_feature_dir: Path,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    len_grid = grid_type.shape[0]
    len_roof = cap_roof_raw.shape[0]
    len_facade = cap_facade_raw.shape[0]
    if len_grid == len_roof == len_facade:
        return grid_type, cap_roof_raw, cap_facade_raw

    idx_non_zero = _indices_non_zero_from_features(city, city_feature_dir)
    n_non_zero = len(idx_non_zero)

    if len_grid > n_non_zero:
        grid_type = grid_type[idx_non_zero]
        len_grid = grid_type.shape[0]
    if len_roof > n_non_zero:
        cap_roof_raw = cap_roof_raw[idx_non_zero]
        len_roof = cap_roof_raw.shape[0]
    if len_facade > n_non_zero:
        cap_facade_raw = cap_facade_raw[idx_non_zero]
        len_facade = cap_facade_raw.shape[0]

    if not (len_grid == len_roof == len_facade):
        raise ValueError(
            f"{city}: failed to align grid_type ({len_grid}), roof capacity ({len_roof}), and facade capacity ({len_facade})."
        )
    return grid_type, cap_roof_raw, cap_facade_raw


def _main_case_installable_areas(
    city: str,
    city_main_row: pd.Series,
    ml_results_dir: Path,
    city_feature_dir: Path,
    grid_type: np.ndarray,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    capacity_dir = ml_results_dir / "Capacity"
    cap_roof_path = capacity_dir / f"Cap_roof_{city}.npy"
    cap_facade_path = capacity_dir / f"Cap_facade_{city}.npy"
    if not cap_roof_path.exists():
        raise FileNotFoundError(f"Missing {cap_roof_path}")
    if not cap_facade_path.exists():
        raise FileNotFoundError(f"Missing {cap_facade_path}")

    cap_roof_raw = np.asarray(np.load(cap_roof_path), dtype=float).reshape(-1)
    cap_facade_raw = np.asarray(np.load(cap_facade_path), dtype=float)
    if cap_facade_raw.ndim == 1:
        cap_facade_ideal = cap_facade_raw.reshape(-1)
    else:
        cap_facade_ideal = cap_facade_raw[:, -1].reshape(-1)

    grid_type, cap_roof_raw, cap_facade_ideal = _align_grid_level_arrays(
        city=city,
        grid_type=grid_type,
        cap_roof_raw=cap_roof_raw,
        cap_facade_raw=cap_facade_ideal,
        city_feature_dir=city_feature_dir,
    )

    roof_scale = _scale_to_saved_total(
        city_main_row["rpv_capacity_GW"], np.sum(cap_roof_raw), city, "RPV capacity"
    )
    facade_scale = _scale_to_saved_total(
        city_main_row["fpv_capacity_GW"], np.sum(cap_facade_ideal), city, "FPV capacity"
    )

    # Convert scaled capacity (GW) to equivalent installable PV area (m2) with
    # one common nominal density so that roof and facade use a consistent area definition.
    roof_area_eq = cap_roof_raw * roof_scale * 1e9 / PV_POWER_DENSITY_W_M2
    facade_area_eq = cap_facade_ideal * facade_scale * 1e9 / PV_POWER_DENSITY_W_M2
    return grid_type, roof_area_eq, facade_area_eq


def _infer_city_year_carbon_factors(r_car_t: np.ndarray, r_pow_buy: np.ndarray) -> np.ndarray:
    n_years = r_car_t.shape[2]
    factors = np.zeros(n_years, dtype=float)
    for y in range(n_years):
        den = np.sum(r_pow_buy[:, 0, y, :, :])
        if den <= 0:
            den = np.sum(r_pow_buy[:, 1, y, :, :])
            num = np.sum(r_car_t[:, 1, y, :, :])
        else:
            num = np.sum(r_car_t[:, 0, y, :, :])
        if den <= 0:
            raise ValueError(f"Cannot infer carbon factor for planning year index {y}: non-positive purchased electricity.")
        factors[y] = num / den
    return factors


def build_optimized_zone_pie_data(
    city_main: pd.DataFrame,
    ml_results_dir: Path,
    opt_results_dir: Path,
    cluster_days_path: Path,
    city_feature_dir: Path,
) -> pd.DataFrame:
    city_stat_path = ml_results_dir / "City_statistic.xlsx"
    grid_type_dir = ml_results_dir / "Grid_type"
    if not city_stat_path.exists():
        raise FileNotFoundError(f"Missing {city_stat_path}")
    if not opt_results_dir.exists():
        raise FileNotFoundError(f"Missing optimization directory: {opt_results_dir}")
    if not cluster_days_path.exists():
        raise FileNotFoundError(f"Missing {cluster_days_path}")

    city_stat = pd.read_excel(city_stat_path, sheet_name="Class_Volume", index_col=0)
    cities = city_stat.index.astype(str).str.strip().tolist()
    city_main = city_main.copy()
    city_main["City"] = city_main["City"].astype(str).str.strip()
    city_main = city_main.set_index("City")
    missing_main = sorted(set(cities).difference(city_main.index))
    extra_main = sorted(set(city_main.index).difference(cities))
    if missing_main or extra_main:
        raise ValueError(
            "City lists disagree between City_statistic.xlsx and the main-case CSV. "
            f"Missing in CSV={missing_main}; extra in CSV={extra_main}"
        )

    cluster_days = np.load(cluster_days_path)
    if cluster_days.ndim != 2 or cluster_days.shape[0] < len(cities):
        raise ValueError(
            f"Clu_days has incompatible shape {cluster_days.shape} for {len(cities)} cities."
        )

    zone_data = pd.DataFrame(
        0.0,
        index=ZONE_ORDER,
        columns=[
            "facade_area",
            "roof_area",
            "fpv_carbon_mitigation_Mt",
            "rpv_carbon_mitigation_Mt",
        ],
    )
    result_files = []

    for city_index, city in enumerate(cities):
        grid_path = grid_type_dir / f"Grid_type_{city}.npy"
        result_path = optimization_result_path(opt_results_dir, city, city_index)
        if not grid_path.exists():
            raise FileNotFoundError(f"Missing {grid_path}")
        if not result_path.exists():
            raise FileNotFoundError(
                f"Missing {result_path}. Confirm that Multi_period_planning.py finished all cities."
            )

        grid_type = np.asarray(np.load(grid_path), dtype=float)
        data = loadmat(
            result_path,
            variable_names=["R_Pow_f", "R_Car", "R_Pow", "R_Pow_Buy", "R_Car_t"],
        )
        required_keys = ["R_Pow_f", "R_Car", "R_Pow", "R_Pow_Buy", "R_Car_t"]
        missing_keys = [key for key in required_keys if key not in data]
        if missing_keys:
            raise KeyError(f"{result_path} is missing arrays: {missing_keys}")
        r_pow_f = np.asarray(data["R_Pow_f"], dtype=float)
        r_car = np.asarray(data["R_Car"], dtype=float)
        r_pow = np.asarray(data["R_Pow"], dtype=float)
        r_pow_buy = np.asarray(data["R_Pow_Buy"], dtype=float)
        r_car_t = np.asarray(data["R_Car_t"], dtype=float)

        city_main_row = city_main.loc[city]
        grid_type, roof_area_eq, facade_area_eq = _main_case_installable_areas(
            city=city,
            city_main_row=city_main_row,
            ml_results_dir=ml_results_dir,
            city_feature_dir=city_feature_dir,
            grid_type=grid_type,
        )

        validate_optimization_arrays(city, grid_type, r_pow_f, r_car, r_pow, r_pow_buy, r_car_t)

        n_typical_days = r_pow_f.shape[2]
        if cluster_days.shape[1] < n_typical_days:
            raise ValueError(
                f"{city}: Clu_days has {cluster_days.shape[1]} columns but R_Pow_f has {n_typical_days} representative days."
            )

        fpv_carbon_grid = np.sum(r_car[:, 0, :], axis=1) - np.sum(r_car[:, 1, :], axis=1)

        carbon_factor_y = _infer_city_year_carbon_factors(r_car_t, r_pow_buy)
        baseline_carbon_grid = np.zeros(grid_type.shape[0], dtype=float)
        for y in range(r_pow.shape[1]):
            load_y = np.zeros(grid_type.shape[0], dtype=float)
            for d in range(n_typical_days):
                load_y += 5 * cluster_days[city_index, d] * np.sum(r_pow[:, y, d, :], axis=1)
            baseline_carbon_grid += carbon_factor_y[y] * load_y
        rpv_carbon_grid = baseline_carbon_grid - np.sum(r_car[:, 0, :], axis=1)

        valid = np.where(grid_type[:, 0] != 888)[0]
        height = grid_type[valid, 1]
        building_count = grid_type[valid, 3]
        zone_masks = {
            "HnD": (height >= 18) & (building_count >= 200),
            "HnS": (height >= 18) & (building_count < 200),
            "MnD": (height < 18) & (building_count >= 200),
            "MnS": (height < 18) & (building_count < 200),
        }

        for zone, mask in zone_masks.items():
            grid_indices = valid[mask]
            zone_data.loc[zone, "facade_area"] += np.sum(facade_area_eq[grid_indices])
            zone_data.loc[zone, "roof_area"] += np.sum(roof_area_eq[grid_indices])
            zone_data.loc[zone, "fpv_carbon_mitigation_Mt"] += np.sum(fpv_carbon_grid[grid_indices])
            zone_data.loc[zone, "rpv_carbon_mitigation_Mt"] += np.sum(rpv_carbon_grid[grid_indices])

        result_files.append(result_path)
        print(f"Loaded optimized pathway: {city} ({city_index + 1}/{len(cities)})")

    if (zone_data.sum(axis=0) <= 0).any():
        raise ValueError(f"Optimization aggregation produced non-positive totals:\n{zone_data}")

    newest = max(path.stat().st_mtime for path in result_files)
    oldest = min(path.stat().st_mtime for path in result_files)
    print(
        f"Optimization source: {opt_results_dir} | files={len(result_files)} | "
        f"mtime range={pd.to_datetime(oldest, unit='s')} to {pd.to_datetime(newest, unit='s')}"
    )
    return zone_data


def draw_fig4b(zone_data: pd.DataFrame, output_dir: Path) -> None:
    values = zone_data[
        [
            "facade_area",
            "roof_area",
            "fpv_carbon_mitigation_Mt",
            "rpv_carbon_mitigation_Mt",
        ]
    ].to_numpy(dtype=float)
    ratios = 100 * values / values.sum(axis=0, keepdims=True)

    pie_titles = [
        "Facade Area",
        "Roof Area",
        "FPV carbon mitigation",
        "RPV carbon mitigation",
    ]

    plt.rc("font", size=FS - 8)
    fig, axes = plt.subplots(2, 2, figsize=np.array([FIGWIDTH * 0.95, FIGWIDTH * 1.05]) / 2.54)
    axes = axes.ravel()
    wedges = None

    for i, ax in enumerate(axes):
        # \u5de6\u4fa7\u4e24\u56fe\u7a81\u51fa HnD；\u53f3\u4fa7\u4e24\u56fe\u7a81\u51fa MnD
        highlight_idx = 2 if i in (1, 3) else 0

        explode = [0, 0, 0, 0]
        explode[highlight_idx] = 0.08

        wedges, _, _ = ax.pie(
            ratios[:, i],
            colors=ZONE_COLORS,
            autopct="%1.1f%%",
            startangle=90,
            textprops={"fontsize": FS - 10},
            pctdistance=0.62,
            radius=1.08,
            shadow=False,
            explode=explode,
        )

        ax.set_title(
            pie_titles[i],
            fontsize=FS - 3,
            fontweight="bold",
        )

        for j, wedge in enumerate(wedges):
            wedge.set_alpha(1.0 if j == highlight_idx else 0.85)
            if j == highlight_idx:
                wedge.set_edgecolor("blue")
                wedge.set_linewidth(1.2)
            else:
                wedge.set_edgecolor("white")
                wedge.set_linewidth(0.8)

    fig.subplots_adjust(
        wspace=0.15,
        hspace=0.10,
        bottom=0.11,
    )

    # \u5355\u72ec\u521b\u5efa\u4e2d\u6027\u7684\u56fe\u4f8b，\u4e0d\u7a81\u51fa\u663e\u793a HnD \u6216\u5176\u4ed6\u7c7b\u578b
    legend_handles = [
        Patch(
            facecolor=color,
            edgecolor="none",
            alpha=0.85,
            label=zone,
        )
        for zone, color in zip(ZONE_ORDER, ZONE_COLORS)
    ]

    fig.legend(
        handles=legend_handles,
        labels=ZONE_ORDER,
        loc="lower center",
        bbox_to_anchor=(0.5, 0.055),
        ncol=4,
        fontsize=FS - 8,
    )
    save_figure(fig, output_dir / "Fig4b.pdf")

    summary = 100 * zone_data.div(zone_data.sum(axis=0), axis=1)
    print("Optimized-pathway Fig. 4b shares (%):")
    print(summary.round(1).to_string())


